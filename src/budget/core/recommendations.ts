import { stats } from "./evaluation";
import { RULES } from "../data/scenario";
import type { GameState } from "./types";

/**
 * Персональные рекомендации.
 *
 * Правила детерминированные: одни и те же входные данные дают один и тот же
 * совет. Это важно — рекомендации объясняют игроку, что именно в его
 * игре привело к результату, а не дают общие слова.
 *
 * Семь рекомендаций взяты из исходного документа «Проверь свой бюджет»,
 * ещё четыре добавлены под счастье и Соломона (раздел 14 документа
 * `docs/Хермес-вариант.md`).
 */
export function recommendations(state: GameState): string[] {
  const s = stats(state);
  const tips: string[] = [];

  if (s.avgMood < 25) {
    tips.push(
      "Выгорание — главный риск. Чередуйте смены с отдыхом: уставший работник получает меньше.",
    );
  }
  if (state.savings === 0) {
    tips.push(
      "Создайте финансовую подушку — это страховка от неожиданных расходов.",
    );
  } else if (state.savings >= RULES.saveBonusAt) {
    tips.push(
      "Резерв сформирован: подушка даёт +1 настроения в день. Не трогайте её без необходимости.",
    );
  }
  if (s.avgSolomon < 40) {
    tips.push(
      "Соломон скучает. Поглаживание бесплатно, а игрушка радует его сильнее всех.",
    );
  }
  if (state.rep < 2) {
    tips.push(
      "Общайтесь с друзьями: репутация открывает репетиторство — самый выгодный заработок.",
    );
  }
  if (state.cash < 0) {
    tips.push(
      "Бюджет в минусе. Подушка — единственный способ не залезть в долг глубже.",
    );
  }
  if (s.audit.byCategory["развлечения"] > 3000) {
    tips.push(
      "Планируйте необязательные расходы: развлечения дорожают в энергии и времени.",
    );
  }
  if (state.spentByCategory["телефон"] >= 12000) {
    tips.push(
      "Сравнивайте ремонт и покупку: ремонт почти вдвое дешевле.",
    );
  }
  if (state.spentByCategory["телефон"] === 0 && state.phoneResolved) {
    tips.push(
      "Старый телефон бесплатен, но бьёт по настроению. Иногда экономия дороже.",
    );
  }
  if (state.spentByCategory["подарки"] >= 5000) {
    tips.push(
      "Дорогой подарок не гарантирует тёплое отношение. Внимание важнее суммы.",
    );
  }
  if (s.avgSolomon < 25) {
    tips.push(
      "Соломон грустит. Уделяйте ему каждый день по минуте — это бесплатно, а без этого всё остальное не работает.",
    );
  }
  if (s.audit.verdict === "Расходы превысили доходы") {
    tips.push(
      "Обязательные траты в доле 50 % и выше — это уже не развлечение, а уход от финансовых решений.",
    );
  }
  if (tips.length === 0) {
    tips.push(
      "Неделя прошла сбалансированно: и деньги есть, и Соломон доволен. Продолжайте в том же духе.",
    );
  }

  return tips.slice(0, 7);
}
